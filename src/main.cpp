float easingCurve(int i, int size) {      
	float out;
	// 先归一化i到0-1范围
	float t = static_cast<float>(i) / (SMOOTH_SIZE - 1);
	// 计算三次缓入缓出
	float value = (t < 0.5f) ? 4 * t * t * t : 1 - 4 * (1 - t) * (1 - t) * (1 - t);
	// 映射到0-SMOOTH_SIZE范围
	out = map(value, 0, 1, 0, SMOOTH_SIZE - 1);
	return out;
}

