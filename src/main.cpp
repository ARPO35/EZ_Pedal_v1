void loop() {
	display.clearDisplay();

	//CC1 Output
	int currentValue = analogRead(15);
	if (abs(deb - currentValue) > 7) {
		deb = currentValue;
		analog1_maped = map(deb, 0, 1023, 0, 127);
		if (analog1_maped < deadzone_s) {
			analog1_output = 0;	
		}
		else if (analog1_maped > deadzone_e) {
			analog1_output = 127;
		}
		else {
			analog1_output = map(analog1_maped, deadzone_s, deadzone_e, 0, 127);
		}
		Serial.print("MidiCC");
		Serial.print(channel);
		Serial.print(": ");
		Serial.print(currentValue);
		Serial.print("	");
		Serial.print(deb);
		Serial.print("	");
		Serial.println(analog1_output);
		usbMidi.sendControlChange(1, analog1_output, channel);
	}

	//Controll
	if (digitalRead(4) == HIGH) {
		bLeft = 100;
	}
	if (bLeft > 0) {
		bLeft -= 1;
		if (digitalRead(4) == LOW) {
			bLeft = 0;
			cLeft = true;
		}
	}
	if (digitalRead(5) == HIGH) {
		bRight = 100;
	}
	if (bRight > 0) {
		bRight -= 1;
		if (digitalRead(5) == LOW) {
			bRight = 0;
			cRight = true;
		}
	}
	if (digitalRead(6) == HIGH) {
		bExit = 100;
	}
	if (bExit > 0) {
		bExit -= 1;
		if (digitalRead(6)) {
			bExit = 0;
			cExit = true;
		}
	}
	if (digitalRead(7) == HIGH) {
		bEnter = 100;
	}
	if (bEnter > 0) {
		bEnter -= 1;
		if (digitalRead(7)) {
			bEnter = 0;
			cEnter = true;
		}
	}

	//Button response
	//main deadzone dev
	if (cLeft) {
		cLeft = false;
		if (level == 0) {
			switchPage(-1);
		}
		else if (level == 1) {
			select_item -= 1;
		}
	}
	if (cRight) {
		cRight = false;
		if (level == 0) {
			switchPage(1);
		}
		else if (level == 1) {
			select_item -= 1;
		}
	}

	//display
	if (page.page == "main") {
		if (page.step < 127) {
			page.step += 1;
			smooth_in = map(smoothValues[map(page.step, 0, 127, 0, SMOOTH_SIZE - 1)], 0, SMOOTH_SIZE - 1, 0, 127);
		}
		//ValueLine
		valueline.y = map(smooth_in, 0, 127, 70, 63);
		for (int i = 0; i < 5; i++) {
			display.drawLine(0, valueline.y - i, analog1_output, valueline.y - i, SSD1306_WHITE);
		}
		display.drawLine(0,   valueline.y - 5, 127, valueline.y - 5, SSD1306_WHITE);
		display.drawLine(0,   valueline.y, 	   127, valueline.y, 	 SSD1306_WHITE);
		display.drawLine(0,   valueline.y, 	   0,   valueline.y - 5, SSD1306_WHITE);
		display.drawLine(127, valueline.y, 	   127, valueline.y - 5, SSD1306_WHITE);
		ShowPageTitle();
	}
	else if (page.page == "deadzon") {
		if (page.step < 127) {
			page.step += 1;
			temp1 = 0;
			temp2 = 0;
			temp3 = 0;
			smooth_in = map(smoothValues[map(page.step, 0, 127, 0, SMOOTH_SIZE - 1)], 0, SMOOTH_SIZE - 1, 0, 127);
		}
		ShowPageTitle();
		deadzone_v();
	}
	else if (page.page == "dev") {
		if (page.step < 127) {
			page.step += 1;
			temp1 = 0;
			temp2 = 0;
			temp3 = 0;
			smooth_in = map(smoothValues[map(page.step, 0, 127, 0, SMOOTH_SIZE - 1)], 0, SMOOTH_SIZE - 1, 0, 127);
		}
		if (temp1 < SMOOTH_SIZE) {
			temp1 += 1;
		}
		else {
			temp1 = 0;
		}
		ShowPageTitle();
		smooth_Circle_Test();
		dev_showcurve();
	}
	
	display.display();
	delay(2);
}
